export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug || p.id === slug);
}

export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}

export function getProductsByCategory(categorySlug: string): Product[] {
  return PRODUCTS.filter((p) => p.categorySlug === categorySlug);
}

export function getProductsByState(stateId: string): Product[] {
  return PRODUCTS.filter((p) => p.stateId === stateId);
}

export function getProductsByRegion(region: string): Product[] {
  return PRODUCTS.filter((p) => p.region.toLowerCase() === region.toLowerCase());
}

export function getTrendingProducts(): Product[] {
  return PRODUCTS.filter((p) => p.isTrending);
}

export function getBestSellers(): Product[] {
  return PRODUCTS.filter((p) => p.isBestSeller);
}
